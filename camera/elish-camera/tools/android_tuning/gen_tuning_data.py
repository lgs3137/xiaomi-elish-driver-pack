#!/usr/bin/env python3
"""Generate src/tuning_data.h from locally extracted Android Chromatix data.

This file is NOT shipped: run it on your own device after
tools/android_tuning/chromatix_extract.py + build_linux_params.py produced
linux-recommended-params.json.  The generated header is ignored by git
(see ../../.gitignore) because it contains per-device calibration data.

Usage:
    tools/android_tuning/gen_tuning_data.py \
        --json /path/to/linux-recommended-params.json \
        --out ../../src/tuning_data.h
"""
import argparse
import json
import os

DEFAULT_OUT = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "tuning_data.h"))

W, H = 17, 13


def pick_ccm(cam):
    entries = cam["ccm"]["entries"]
    best = None
    for e in entries:
        lo, hi = e["cct"][0], e["cct"][1]
        if lo >= 6000.0 and hi >= 6500.0:
            return e["m3x3"], (lo, hi)
        if best is None or lo > best[1][0]:
            best = (e["m3x3"], (lo, hi))
    return best


def fmt_mat(m):
    return ", ".join("%.6ff" % v for row in m for v in row)


def emit_cam(f, key, cam):
    chans = cam["lsc"]["channels"]
    assert len(chans) == 4 and all(len(c) == W * H for c in chans), key
    f.write("static const float elish_lsc_%s[4][%d] = {\n" % (key, W * H))
    for c in range(4):
        vals = ", ".join("%.6ff" % v for v in chans[c])
        f.write("    { %s },\n" % vals)
    f.write("};\n\n")
    m, cct = pick_ccm(cam)
    f.write("/* CCM for CCT %g..%g K, row-major */\n" % cct)
    f.write("static const float elish_ccm_%s[9] = { %s };\n\n" % (key, fmt_mat(m)))


def main():
    ap = argparse.ArgumentParser(description='生成本地 tuning_data.h（不随包分发）')
    ap.add_argument('--json', default='linux-recommended-params.json', help='build_linux_params.py 输出')
    ap.add_argument('--out', default=DEFAULT_OUT, help='生成的 C 头文件路径')
    a = ap.parse_args()
    path = a.json
    with open(path) as fh:
        d = json.load(fh)
    cams = d["cameras"]
    with open(a.out, "w") as f:
        f.write("/* Generated by tools/gen_tuning_data.py - do not edit by hand.\n")
        f.write(" * Source: locally extracted Android Chromatix bins (do not redistribute).\n")
        f.write(" * LSC channel order per QTI convention: R, Gr, Gb, B.\n")
        f.write(" * Grid: %d rows x %d cols (sensor space). CCM applied after WB. */\n\n" % (H, W))
        f.write("#ifndef ELISH_TUNING_DATA_H\n#define ELISH_TUNING_DATA_H\n\n")
        f.write("#define ELISH_LSC_GRID_W %d\n#define ELISH_LSC_GRID_H %d\n" % (W, H))
        f.write("#define ELISH_TUNING_AVAILABLE 1\n\n")
        emit_cam(f, "rear_wide", cams["rear_wide"])
        emit_cam(f, "front", cams["front"])
        f.write("#endif /* ELISH_TUNING_DATA_H */\n")
    print("wrote", os.path.normpath(a.out))


if __name__ == "__main__":
    main()
